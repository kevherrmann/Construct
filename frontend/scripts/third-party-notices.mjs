// Erzeugt ../THIRD_PARTY_NOTICES.md aus den Paketen, die im Build landen
// (npm-Abhängigkeiten ohne dev). Nach Paket-Updates neu laufen lassen:
//   npm run notices
// Die Schriften (OFL-1.1) verlangen, dass Copyright und Lizenztext mit
// ausgeliefert werden — darum stehen ihre Zeilen und die OFL hier vollständig.
import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const tree = JSON.parse(execSync('npm ls --omit=dev --all --json', { maxBuffer: 1e8 }).toString())
const pkgs = new Map()
;(function walk(deps) {
  for (const [name, d] of Object.entries(deps ?? {})) {
    if (!pkgs.has(name)) {
      const p = JSON.parse(readFileSync(join('node_modules', name, 'package.json'), 'utf8'))
      const license = typeof p.license === 'string' ? p.license : (p.license?.type ?? 'UNKNOWN')
      const repo =
        typeof p.repository === 'string' ? p.repository : (p.repository?.url ?? p.homepage ?? '')
      pkgs.set(name, {
        version: d.version,
        license,
        repo: repo.replace(/^git\+/, '').replace(/\.git$/, ''),
      })
    }
    walk(d.dependencies)
  }
})(tree.dependencies)

const rows = [...pkgs].sort(([a], [b]) => a.localeCompare(b))
const fonts = rows.filter(([, p]) => p.license === 'OFL-1.1')
const copyright = (name) => {
  for (const f of ['LICENSE', 'LICENSE.txt', 'LICENSE.md', 'OFL.txt']) {
    const path = join('node_modules', name, f)
    if (existsSync(path))
      return (
        readFileSync(path, 'utf8')
          .split('\n')
          .map((l) => l.trim())
          // Die erste Zeile, die mit "Copyright" beginnt — ohne Dateinamen-Zusätze.
          .find((l) => /^copyright\b/i.test(l))
          ?.split(/\s\S+\.ttf:/)[0] ?? ''
      )
  }
  return ''
}
const ofl = (() => {
  const f = join('node_modules', fonts[0][0], 'LICENSE')
  const t = readFileSync(f, 'utf8')
  const i = t.indexOf('SIL OPEN FONT LICENSE')
  return i >= 0 ? t.slice(i).trim() : t.trim()
})()

const out = `# Third-party notices

CONSTRUCT itself is licensed under the terms in [LICENSE](LICENSE). The built
interface in \`static/app/\` bundles the following open-source packages. Their
licenses allow redistribution; this file keeps the notices they require.

Generated by \`frontend/scripts/third-party-notices.mjs\` — do not edit by hand.

Python dependencies (\`requirements*.txt\`) are not bundled; pip installs them
from PyPI under their own licenses.

## JavaScript packages

| Package | Version | License |
|---|---|---|
${rows.map(([n, p]) => `| ${p.repo ? `[${n}](${p.repo.replace(/^git:/, 'https:')})` : n} | ${p.version} | ${p.license} |`).join('\n')}

## Fonts

The fonts are licensed under the SIL Open Font License 1.1 (full text below).

${fonts.map(([n]) => `- **${n}** — ${copyright(n) || 'see the package license'}`).join('\n')}

\`\`\`
${ofl}
\`\`\`
`
writeFileSync(new URL('../../THIRD_PARTY_NOTICES.md', import.meta.url), out)
console.log(`${rows.length} Pakete, davon ${fonts.length} Schriften → THIRD_PARTY_NOTICES.md`)
